/* eslint-disable @typescript-eslint/no-explicit-any */
import { i18nLanguageParse, i18nPluralKeys } from '@helpers/i18n/i18n-parse';
import { i18nValidate } from '@helpers/i18n/i18n-validate';
import type { I18nLanguageData, I18nLanguageInfo } from '@interfaces';
import { sortBy } from 'es-toolkit/compat';
import fs from 'fs-extra';
import * as yaml from 'js-yaml';
import path from 'path';
import rec from 'recursive-readdir';
import { CONTENT_OUT_DIR } from './content-out-dir';
import { i18nTiledObjectNames } from '@helpers/i18n/i18n-fields';
import { writeJsonIfChanged } from './write-json-if-changed';

import { I18N_DIR } from './i18n-dir';
const I18N_SOURCE_DIR = path.join('gamedata', I18N_DIR);
const I18N_OUT_DIR = `${CONTENT_OUT_DIR}/i18n`;
const BASE_LOCALE = 'en';
const KEYS_FILE = 'src/app/interfaces/i18n-keys.ts';

const readLanguageDocs = async (
  dir: string,
): Promise<Record<string, unknown>> => {
  const files = sortBy(await rec(dir)).filter((file: string) =>
    file.endsWith('.yml'),
  );
  return Object.fromEntries(
    files.map((file: string) => [
      path.relative(dir, file).replace(/\\/g, '/'),
      yaml.load(fs.readFileSync(file, 'utf-8')),
    ]),
  );
};

const mapNodeNames = (): string[] =>
  fs
    .readdirSync('gamemaps')
    .filter((file: string) => file.endsWith('.json'))
    .flatMap((file: string) =>
      i18nTiledObjectNames(fs.readJsonSync(path.join('gamemaps', file))),
    );

const writeKeysFile = (uiDoc: unknown, ui: Record<string, string>) => {
  const pluralKeys = i18nPluralKeys(uiDoc);
  const isPluralForm = (key: string) =>
    pluralKeys.some((plural) => key.startsWith(`${plural}.`));
  const union = (keys: string[]) =>
    keys.length === 0
      ? ' never'
      : sortBy(keys)
          .map((key) => `\n  | '${key}'`)
          .join('');

  const body = [
    '// Generated by `npm run gamedata:build` from gamedata/i18n/en/ui.yml. Do not edit.',
    `export type I18nKey =${union(Object.keys(ui).filter((key) => !isPluralForm(key)))};`,
    '',
    `export type I18nPluralKey =${union(pluralKeys)};`,
    '',
  ].join('\n');

  if (fs.existsSync(KEYS_FILE) && fs.readFileSync(KEYS_FILE, 'utf-8') === body)
    return;
  fs.writeFileSync(KEYS_FILE, body);
};

const parseLanguage = (
  locale: string,
  docs: Record<string, unknown>,
  contentTypes: string[],
): I18nLanguageData => {
  const { language, errors } = i18nLanguageParse(docs, contentTypes);
  if (language && language.locale !== locale) {
    errors.push(`folder name must match its locale "${language.locale}".`);
  }
  if (!language || errors.length > 0) {
    errors.forEach((error) => console.error(`i18n/${locale}: ${error}`));
    process.exit(1);
  }
  return language;
};

const validateLanguage = (
  language: I18nLanguageData,
  english: I18nLanguageData,
  allData: Record<string, any[]>,
  nodeNames: string[],
) => {
  const { errors, warnings } = i18nValidate(
    language,
    english.ui,
    (type, name) => allData[type]?.find((entry) => entry.name === name),
    nodeNames,
  );
  warnings.forEach((warning) =>
    console.warn(`i18n/${language.locale}: ${warning}`),
  );
  errors.forEach((error) => console.error(`i18n/${language.locale}: ${error}`));
  if (errors.length > 0) process.exit(1);
};

// Runs before content ids are rewritten, so translations are checked against the English names they're keyed by.
export const buildI18n = async (
  allData: Record<string, any[]>,
): Promise<I18nLanguageData[]> => {
  const contentTypes = Object.keys(allData);
  const locales = sortBy(
    fs
      .readdirSync(I18N_SOURCE_DIR)
      .filter((name: string) =>
        fs.statSync(path.join(I18N_SOURCE_DIR, name)).isDirectory(),
      ),
  );
  const docsByLocale = await Promise.all(
    locales.map((locale) =>
      readLanguageDocs(path.join(I18N_SOURCE_DIR, locale)),
    ),
  );

  const languages = locales.map((locale, i) =>
    parseLanguage(locale, docsByLocale[i], contentTypes),
  );
  const english = languages.find((lang) => lang.locale === BASE_LOCALE);
  if (!english) {
    console.error(`i18n: missing the base language folder "${BASE_LOCALE}".`);
    process.exit(1);
  }

  const nodeNames = mapNodeNames();
  languages
    .filter((lang) => lang !== english)
    .forEach((lang) => validateLanguage(lang, english, allData, nodeNames));

  writeKeysFile(
    docsByLocale[locales.indexOf(BASE_LOCALE)]['ui.yml'],
    english.ui,
  );
  return languages;
};

// Keeps only text for content that shipped, so a demo build can't leak names and descriptions of cut content.
const pruneContent = (
  language: I18nLanguageData,
  allData: Record<string, any[]>,
): I18nLanguageData => {
  const keep = (type: string, entries: Record<string, unknown>) => {
    const names = new Set((allData[type] ?? []).map((entry) => entry.name));
    return Object.fromEntries(
      Object.entries(entries).filter(([name]) => names.has(name)),
    );
  };
  return {
    ...language,
    content: Object.fromEntries(
      Object.entries(language.content).map(([type, entries]) => [
        type,
        keep(type, entries),
      ]),
    ) as I18nLanguageData['content'],
    sources: {},
    uiSources: {},
  };
};

export const writeI18n = (
  languages: I18nLanguageData[],
  allData: Record<string, any[]>,
) => {
  fs.ensureDirSync(I18N_OUT_DIR);
  languages.forEach((lang) =>
    writeJsonIfChanged(
      `${I18N_OUT_DIR}/${lang.locale}.json`,
      pruneContent(lang, allData),
    ),
  );
  const index: I18nLanguageInfo[] = languages.map(
    ({ locale, languageName }) => ({ locale, languageName }),
  );
  writeJsonIfChanged(`${I18N_OUT_DIR}/languages.json`, index);
  console.log(
    `Built ${languages.length} language(s): ${languages.map((lang) => lang.locale).join(', ')}`,
  );
};
