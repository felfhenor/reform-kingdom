import fontkit from 'fontkit';
import fs from 'fs-extra';
import { sortBy } from 'es-toolkit/compat';
import path from 'path';

const FONT_DIR = 'public/font/input';
const OUT_FILE = 'src/app/ff/input/ff-glyph-codes.ts';

// Font file -> [exported constant, Kenney's name prefix]. Only that exact prefix is dropped, since fonts
// also hold variants (playstation5_*, controller_*) that would collide without theirs.
const FAMILIES: Record<string, [string, string]> = {
  xbox: ['FF_GLYPH_XBOX', 'xbox_'],
  playstation: ['FF_GLYPH_PLAYSTATION', 'playstation_'],
  switch: ['FF_GLYPH_SWITCH', 'switch_'],
  switch2: ['FF_GLYPH_SWITCH2', 'switch_'],
  'steam-controller': ['FF_GLYPH_STEAM_CONTROLLER', 'steam_'],
  'steam-deck': ['FF_GLYPH_STEAM_DECK', 'steamdeck_'],
};

function glyphKey(name: string, prefix: string): string {
  return name.startsWith(prefix) ? name.slice(prefix.length) : name;
}

// The curves' true extent; rounded since fontkit evaluates them in fractional units.
function inkHeight(glyph: fontkit.Glyph): number {
  return Math.round(glyph.bbox.maxY - glyph.bbox.minY);
}

function familyEntries(file: string, prefix: string): string[] {
  const font = fontkit.openSync(path.join(FONT_DIR, `${file}.woff2`));
  if (!('characterSet' in font)) throw new Error(`${file} is a collection`);

  const entries = font.characterSet
    .map((code) => ({ code, glyph: font.glyphForCodePoint(code) }))
    .filter(({ glyph }) => glyph.name?.includes('_'))
    .map(({ code, glyph }) => ({
      key: glyphKey(glyph.name, prefix),
      code,
      inkHeight: inkHeight(glyph),
    }));
  const keys = entries.map((entry) => entry.key);
  const duplicate = keys.find((key, index) => keys.indexOf(key) !== index);
  if (duplicate) throw new Error(`${file}: duplicate glyph key ${duplicate}`);

  return sortBy(entries, 'key').map(
    ({ key, code, inkHeight }) =>
      `  ${key}: { code: 0x${code.toString(16)}, inkHeight: ${inkHeight} },`,
  );
}

function familyConstant(file: string, [constant, prefix]: [string, string]) {
  const lines = familyEntries(file, prefix).join('\n');
  return `export const ${constant} = {\n${lines}\n} as const satisfies Record<string, FFGlyphCode>;`;
}

const body = Object.entries(FAMILIES).map(([file, family]) =>
  familyConstant(file, family),
);

fs.writeFileSync(
  OUT_FILE,
  [
    '// Generated by scripts/build-glyphs.ts from the Kenney fonts in public/font/input; run `npm run build:glyphs` after changing them.',
    "import type { FFGlyphCode } from '@ff/interfaces/ff-input';",
    '',
    body.join('\n\n'),
    '',
  ].join('\n'),
);
console.info(`Wrote ${OUT_FILE}!`);
